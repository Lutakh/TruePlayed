if type(reg) ~= "table" then
  reg = {}
  ns.LOCALES = reg
end
reg[CODE] = L
-- The default ("auto") on a client in this language: this language from file load on.
if GetLocale() == CODE then
  local dst = ns.L
  if type(dst) == "table" then
    for k, v in pairs(L) do dst[k] = v end
  end
end
